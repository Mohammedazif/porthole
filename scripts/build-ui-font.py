#!/usr/bin/env python3
"""Embed the UI typefaces: Geist and Geist Mono, both variable-weight fonts.
FreeType picks each weight from them and rasterizes at the actual display pixel size."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
fonts = root / 'src/ui/fonts'
dest = root / 'src/ui/generated/font_face.h'
with dest.open('w') as out:
    out.write('/* Generated by scripts/build-ui-font.py. Geist and Geist Mono (SIL OFL 1.1);\n'
              ' * see ui/fonts/LICENSE. */\n')
    for name, ttf in (('font_sans_bytes', 'Geist.ttf'), ('font_mono_bytes', 'GeistMono.ttf')):
        data = (fonts / ttf).read_bytes()
        out.write(f'static const unsigned char {name}[] = {{\n')
        for i in range(0, len(data), 24):
            out.write(','.join(map(str, data[i:i + 24])) + ',\n')
        out.write('};\n')
        print(f'{ttf}: {len(data)} bytes')
print(dest)
