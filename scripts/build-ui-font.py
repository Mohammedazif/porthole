#!/usr/bin/env python3
"""Embed the UI typeface. FreeType rasterizes it at the actual display pixel size."""
import argparse
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', default='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
data = Path(args.font).read_bytes()
dest = root / 'src/ui/generated/font_face.h'
with dest.open('w') as out:
    out.write('/* Generated by scripts/build-ui-font.py. DejaVu Sans; see ui/fonts/LICENSE. */\n')
    out.write('static const unsigned char font_face_bytes[] = {\n')
    for i in range(0, len(data), 24):
        out.write(','.join(map(str, data[i:i+24])) + ',\n')
    out.write('};\n')
print(f'{dest}: {len(data)} embedded font bytes')
